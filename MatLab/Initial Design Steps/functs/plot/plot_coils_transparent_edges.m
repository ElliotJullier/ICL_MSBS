function h = plot_coils_transparent_edges(ax, coils)
% Plot coil bodies with transparent faces and black edges.
%
% Supports either:
%   - struct geometry with .Faces and .Vertices
%   - alphaShape geometry

nCoils = numel(coils);
h = gobjects(nCoils, 1);

for k = 1:nCoils
    shp = coils(k).shp;

    if isempty(shp)
        continue
    end

    if isstruct(shp) && isfield(shp, 'Faces') && isfield(shp, 'Vertices')
        h(k) = patch(ax, ...
            'Faces', shp.Faces, ...
            'Vertices', shp.Vertices, ...
            'FaceColor', [0.65 0.65 0.65], ...
            'FaceAlpha', 0.08, ...
            'EdgeColor', 'k', ...
            'LineWidth', 1.25, ...
            'HandleVisibility', 'off', ...
            'HitTest', 'off');

    else
        % alphaShape fallback
        hp = plot(ax, shp);
        set(hp, ...
            'FaceColor', [0.65 0.65 0.65], ...
            'FaceAlpha', 0.08, ...
            'EdgeColor', 'k', ...
            'LineWidth', 1.25, ...
            'HandleVisibility', 'off', ...
            'HitTest', 'off');
        h(k) = hp;
    end
end

end