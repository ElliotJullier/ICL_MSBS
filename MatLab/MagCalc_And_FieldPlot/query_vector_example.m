        "Group","vector_uniform","Seeding","uniform"), ...
    create_vector_plane_query("xz",0,"ULimits",[-.8 .8],"VLimits",[-1.4 1.4], ...
        "Resolution",[41 61],"MaxArrows",300,"Name","Projected B - variation", ...
        "Group","vector_variation","Seeding","variation"), ...
