function P = gradientCoordinateTransform()
%GRADIENTCOORDINATETRANSFORM Map orthonormal STF coordinates to physical ones.
% q are five orthonormal symmetric trace-free coordinates and
% p=P*q gives p=[gxx gyy gxy gxz gyz]. Therefore ||q||_2=||G||_F.
P=[ 1/sqrt(2),  1/sqrt(6), 0,         0,         0; ...
   -1/sqrt(2),  1/sqrt(6), 0,         0,         0; ...
    0,          0,         1/sqrt(2), 0,         0; ...
    0,          0,         0,         1/sqrt(2), 0; ...
    0,          0,         0,         0,         1/sqrt(2)];
end
